#include <stdio.h>
int main()
{
    int r, c;
    scanf("%d %d", &r, &c);
    int a[r][c];
    for (int i = 0; i < r; i++)
    {
        for (int j = 0; j < c; j++)
        {
            scanf("%d", &a[i][j]);
        }
    }

    int flag = 0;
    for (int i = 0; i < r; i++)
    {
        for (int j = 0; j < c; j++)
        {
            if (a[i][j] != 0)
            {
                flag = 1;
            }
        }
    }
    // printf("%d", flag);
    if (flag == 0)
    {
        printf("Zero Matrix");
    }
    else{
        printf("Not Zero");
    }

    return 0;
}